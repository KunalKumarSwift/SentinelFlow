"""Incident report facts and their deterministic Markdown rendering.

The facts section is generated by code, never by the LLM, so every report contains a
correct record even if the narrative above it is weak or missing.
"""

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class ActionLine:
    """One proposed action and how its approval ended."""

    kind: str
    target: str
    status: str


@dataclass(frozen=True, slots=True)
class ReportFacts:
    """Everything a report states as fact (user identifiers already pseudonymised)."""

    incident_id: str
    status: str
    severity: str
    verdict: str
    injection: tuple[str, ...]
    techniques: tuple[str, ...]
    actions: tuple[ActionLine, ...]
    executed: tuple[str, ...]


def render_facts(facts: ReportFacts) -> str:
    """Return the verified facts as a Markdown section."""
    lines = [
        "## Facts (verified from the audit trail)",
        "",
        f"- Incident: {facts.incident_id} ({facts.status})",
        f"- Severity: {facts.severity}; verdict: {facts.verdict}",
        f"- Prompt-injection indicators: {', '.join(facts.injection) or 'none'}",
        f"- ATT&CK techniques: {', '.join(facts.techniques) or 'none identified'}",
        f"- Executed actions: {', '.join(facts.executed) or 'none'}",
        "",
        *_actions_table(facts.actions),
    ]
    return "\n".join(lines)


def _actions_table(actions: tuple[ActionLine, ...]) -> list[str]:
    if not actions:
        return ["No actions were proposed."]
    rows = [f"| {a.kind} | {a.target} | {a.status} |" for a in actions]
    return ["| Action | Target | Approval |", "|---|---|---|", *rows]
